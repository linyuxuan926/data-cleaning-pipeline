"""Create missing local secrets, preserving existing credentials. Stdlib only."""
from pathlib import Path
import secrets


def main() -> None:
    target = Path(__file__).resolve().parents[1] / ".env"
    values = {
        "DB_PASSWORD": secrets.token_hex(24),
        "DB_ROOT_PASSWORD": secrets.token_hex(24),
        "RABBITMQ_USER": "cleaning",
        "RABBITMQ_PASSWORD": secrets.token_hex(24),
        "MINIO_ACCESS_KEY": "cleaning-admin",
        "MINIO_SECRET_KEY": secrets.token_hex(24),
        "INTERNAL_API_TOKEN": secrets.token_hex(32),
        "WEB_PORT": "8088",
        "BOOTSTRAP_ADMIN_USERNAME": "admin_" + secrets.token_hex(4),
        "BOOTSTRAP_ADMIN_PASSWORD": secrets.token_urlsafe(24),
    }
    existing = target.read_text(encoding="utf-8") if target.exists() else ""
    configured = {line.split("=", 1)[0].strip() for line in existing.splitlines()
                  if "=" in line and not line.lstrip().startswith("#")}
    missing = {key: value for key, value in values.items() if key not in configured}
    if not missing:
        print(".env already contains all required keys; credentials were preserved.")
        return
    with target.open("a" if target.exists() else "x", encoding="utf-8", newline="\n") as stream:
        stream.write("\n# Missing deployment keys generated by scripts/bootstrap.py; do not commit.\n")
        stream.writelines(f"{key}={value}\n" for key, value in missing.items())
    try:
        target.chmod(0o600)
    except OSError:
        pass
    print("Generated missing .env keys; existing credentials preserved. Administrator login is stored in .env.")
    print("Run docker compose up -d --build. No secrets were printed.")


if __name__ == "__main__":
    main()
